def _snake(name):
    """CamelCase -> snake_case (matches the YAML condition spelling)."""
    s = re.sub(r"(.)([A-Z][a-z]+)", r"\1_\2", name)
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s)
    return s.lower()


def _snake_table(d):
    return {_snake(k): v for k, v in d.items()}


